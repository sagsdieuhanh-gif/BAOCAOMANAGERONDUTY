'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
require('../v21-shuttle-model.js');require('../v24-shuttle-grid.js');require('../v21-shuttle-export.js');
const model=globalThis.SagsShuttleModel,grid=globalThis.SagsShuttleGridV24._test,exp=globalThis.SagsShuttleExport._test;
const data=['DH','PVHK','KTS','QA_IT'].map((unit,i)=>({unit,direction:'CXR_NHA',departure_min:990,line_no:0,quantity:[20,15,10,5][i]}));
const rows=grid.assemble(data,[]);
const html=grid.makeGrid('CXR_NHA',rows,'DH');
assert.ok(html.includes('v24-table-scroll')&&html.includes('data-v24-value="DH"'));
assert.equal((html.match(/<th scope="col">/g)||[]).length,6,'Only time, four departments and total');
assert.ok(!html.includes('v306-vehicle-showcase')&&!html.includes('GỢI Ý XE')&&!html.includes('shuttle-29.webp'),'No vehicle advice or icons in entry');
assert.ok(html.includes('50</b>'),'Live total still shown');
assert.equal(model.suggestVehicles(50).n45,1);
assert.deepEqual(rows.filter(x=>x.direction==='CXR_NHA').map(x=>x.departure_min),exp.normalize(data,[]).filter(x=>x.direction==='CXR_NHA').map(x=>x.departure_min));
const index=fs.readFileSync('index.html','utf8');
assert.ok(index.includes('v24-shuttle-grid.js?v=3.11')&&index.includes('v300-workspace.css?v=3.19'));
console.log('PASS V3.11: simple headcount entry hides all bus suggestions, export remains compatible');