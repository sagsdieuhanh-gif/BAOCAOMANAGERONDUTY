'use strict';
const assert=require('node:assert/strict');
require('../v21-shuttle-model.js');
const m=globalThis.SagsShuttleModel;
assert.equal(m.defaults.length,7,'Only seven official departure times remain');
assert.deepEqual(m.defaults.filter(x=>x.direction==='NHA_CXR').map(x=>x.departure_min),[420,1050,1170]);
assert.deepEqual(m.defaults.filter(x=>x.direction==='CXR_NHA').map(x=>x.departure_min),[990,1110,1560,1935]);
assert.equal(m.clock(1935),'08:15');
assert.equal(m.clock(1560),'02:00');
assert.equal(m.parseClock('08:15',true),1935);
assert.equal(m.parseClock('25:00',false),null);
assert.equal(m.isDefault('CXR_NHA',510),false,'08:30 is not official');
assert.ok(m.isNextDay(1935)&&!m.isNextDay(990));
console.log('PASS V3.11 seven official shuttle times and 08:15 next-day labeling');
